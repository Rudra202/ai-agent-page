import { createReadStream } from 'node:fs';
import { mkdir, open, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { pipeline } from 'node:stream/promises';
import { measure } from './measure.js';
import type { StorageProvider } from './types.js';

/** <owner>/<name>.<ext>, with only characters that cannot form a path trick. */
const KEY_PATTERN = /^[A-Za-z0-9_-]{1,64}\/[A-Za-z0-9-]{1,64}\.(pdf|png|jpg)$/;

export interface LocalStorage extends StorageProvider {
  /** Absolute path for a valid key. Throws for anything else. Exposed for tests and tooling only. */
  resolvePath(key: string): string;
}

/**
 * Local-disk storage. Keys are generated by the server and checked against a
 * strict pattern, and the resolved path must stay inside the root directory, so
 * a user-supplied file name can never decide where a file is written or read.
 *
 * Documents that were uploaded before GridFS was introduced live here, so reading and deleting
 * stay supported for them.
 */
export function createLocalStorage(rootDir: string): LocalStorage {
  const root = path.resolve(rootDir);

  const resolvePath = (key: string): string => {
    if (!KEY_PATTERN.test(key)) throw new Error('Invalid storage key');
    const full = path.resolve(root, key);
    if (!full.startsWith(root + path.sep)) throw new Error('Invalid storage key');
    return full;
  };

  return {
    name: 'local',
    resolvePath,

    async put(key, data) {
      const full = resolvePath(key);
      await mkdir(path.dirname(full), { recursive: true, mode: 0o700 });
      // "wx" fails if the file exists, so an upload can never replace another file.
      await writeFile(full, data, { flag: 'wx', mode: 0o600 });
      return key;
    },

    async putStream(key, source, meta) {
      const full = resolvePath(key);
      await mkdir(path.dirname(full), { recursive: true, mode: 0o700 });
      // Opening first, exclusively: if the file already exists this throws and NOTHING is removed,
      // so a failed upload can never delete someone else's file. Only a file created here is cleaned up.
      const handle = await open(full, 'wx', 0o600);
      const measured = measure(meta.maxBytes);
      try {
        await pipeline(source, measured.transform, handle.createWriteStream());
      } catch (error) {
        await rm(full, { force: true });
        throw error;
      }
      return { ref: key, ...measured.result() };
    },

    async getStream(ref) {
      let full: string;
      try {
        full = resolvePath(ref);
      } catch {
        return null;
      }
      try {
        const info = await stat(full);
        if (!info.isFile()) return null;
        return { stream: createReadStream(full), size: info.size };
      } catch {
        return null;
      }
    },

    async delete(ref) {
      let full: string;
      try {
        full = resolvePath(ref);
      } catch {
        // Not a key this provider could ever have created, so there is nothing to remove.
        return;
      }
      await rm(full, { force: true });
    },
  };
}
